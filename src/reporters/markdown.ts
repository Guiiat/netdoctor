import { redactText } from "../redact.js";
import type { DiagnosticReport } from "../types.js";

export function renderMarkdown(report: DiagnosticReport): string {
  const lines = [
    "# NetDoctor diagnostic report",
    "",
    `Generated: ${report.generatedAt}`,
    `Duration: ${report.durationMs} ms · Timeout: ${report.options.timeoutMs} ms · Strict: ${report.options.strict ? "yes" : "no"}`,
    "",
    "| Status | Check | Target | Time | Result |",
    "| --- | --- | --- | ---: | --- |",
  ];
  for (const check of report.checks) {
    lines.push(
      `| ${statusMark(check.status)} ${check.status.toUpperCase()} | ${check.category.toUpperCase()} | ${escapeCell(check.target)} | ${check.durationMs} ms | ${escapeCell(check.summary)} |`,
    );
  }
  lines.push(
    "",
    "## Summary",
    "",
    `- Passed: ${report.summary.pass}`,
    `- Warnings: ${report.summary.warn}`,
    `- Failed: ${report.summary.fail}`,
    `- Skipped: ${report.summary.skip}`,
    `- Exit code: ${report.exitCode}`,
  );

  const recommendations = uniqueRecommendations(report);
  if (recommendations.length > 0) {
    lines.push("", "## Recommended actions", "");
    for (const recommendation of recommendations) {
      lines.push(`- ${redactText(recommendation)}`);
    }
  }
  lines.push("", "_Generated by [NetDoctor](https://github.com/Guiiat/netdoctor)._", "");
  return lines.join("\n");
}

function uniqueRecommendations(report: DiagnosticReport): string[] {
  return [
    ...new Set(
      report.checks
        .map((check) => check.recommendation)
        .filter((value): value is string => value !== undefined),
    ),
  ];
}

function escapeCell(value: string): string {
  return redactText(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replace(/([\\|`*_[\]])/g, "\\$1");
}

function statusMark(status: "pass" | "warn" | "fail" | "skip"): string {
  switch (status) {
    case "pass":
      return "✅";
    case "warn":
      return "⚠️";
    case "fail":
      return "❌";
    case "skip":
      return "⏭️";
  }
}
